"""Generate data-only desktop bindings from the Go configuration catalog."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
clients = json.loads((root / "backend/internal/agent/client-catalog.json").read_text(encoding="utf-8"))
assert len({c["id"] for c in clients}) == len(clients)
ts = "// Generated by scripts/sync-client-catalog.py; edit the Go JSON catalog.\n"
ts += "export const extraClients = " + json.dumps(clients, ensure_ascii=False, indent=2) + " as const;\n"
ts += 'export type ExtraClient = (typeof extraClients)[number]["id"];\n'
ts += 'export const extraClientNames = Object.fromEntries(extraClients.map(c => [c.id,c.name])) as Record<ExtraClient,string>;\n'
ts += 'export function isExtraClient(id: string): id is ExtraClient { return extraClients.some(c => c.id === id); }\n'
ts += 'export function clientDefinition(id: ExtraClient) { return extraClients.find(c => c.id === id)!; }\n'

primaries = [("Codex", "codex"), ("ClaudeDesktop", "claude_desktop"), ("ClaudeCli", "claude_cli")]
variants = primaries + [(c["id"].capitalize(), c["id"]) for c in clients]
rs = "// Generated by scripts/sync-client-catalog.py; data-only IPC identifiers.\n"
rs += '#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\npub enum ClientKind {\n'
rs += ''.join(f'    #[serde(rename = "{id}")]\n    {v},\n' for v, id in variants) + '}\n'
rs += 'impl ClientKind {\n    pub fn id(self) -> &\'static str { match self {\n'
rs += ''.join(f'        Self::{v} => "{id}",\n' for v, id in variants) + '    }}\n'
rs += '    pub fn target(self) -> Option<Target> { match self {\n'
rs += ''.join(f'        Self::{v} => Some(Target::{v}),\n' for v, _ in primaries) + '        _ => None,\n    }}\n'
rs += '    pub const EXTRAS: &\'static [Self] = &[\n' + ''.join(f'        Self::{v},\n' for v, _ in variants[3:]) + '    ];\n}\n'
for path, text in [(root / "src/content/clients.ts", ts), (root / "src-tauri/src/client_kind.rs", rs)]:
    if "--check" in sys.argv:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            raise SystemExit(f"Client binding is stale: {path}")
    else:
        path.write_text(text, encoding="utf-8", newline="\n")
